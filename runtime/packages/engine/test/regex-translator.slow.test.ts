/// <reference types="node" />
// Golden test of the Python-regex translator of the workspace migration (design 01 section 2.8, ADR 0002 amended,
// ADR 0067, plan WP-92). Every accepted pattern is translated to the dialect and read back with the runtime compiler.
// Data: fixtures/regex-translator/{regex-golden,regex-rejects}.frozen.json, written by the pre-4.0 gen_regex_golden.py.
// Every expectation is a result CPython produced, frozen as committed data (ADR 0066); this file only compares and
// runs no Python.
import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

import { describe, expect, it } from 'vitest';
import { z } from 'zod';

import { translateToDialect, type PyRegexContext } from '../src/migrate/regex/index.ts';
import { compileRegex, type CompiledRegex } from '../src/regex/index.ts';

const Meta = z.object({ python: z.string(), unicode: z.string(), seed: z.number() });
const Expected = z.union([
  z.null(),
  z.object({
    span: z.tuple([z.number(), z.number()]),
    groups: z.array(z.string().nullable()),
    groupdict: z.record(z.string(), z.string().nullable()),
  }),
]);
const Context = z.enum(['session_rule', 'attempts']);
const Golden = z.object({
  meta: Meta,
  assigned: z.array(z.tuple([z.number(), z.number()])),
  classes: z.array(z.object({ pattern: z.string(), ranges: z.array(z.tuple([z.number(), z.number()])) })),
  cases: z.array(
    z.object({
      kind: z.enum(['table', 'v9', 'random']),
      pattern: z.string(),
      context: Context,
      inputs: z.array(z.string()),
      expected: z.array(Expected),
    }),
  ),
});
const Rejects = z.object({
  meta: Meta,
  rejects: z.array(
    z.object({
      pattern: z.string(),
      context: Context,
      code: z.enum(['SYNTAX', 'UNSUPPORTED_CONSTRUCT', 'UNSUPPORTED_FLAG', 'INEXACT_SEMANTICS', 'JS_COMPILE']),
      pythonError: z.string().nullable(),
    }),
  ),
});

const DIR = new URL('fixtures/regex-translator/', import.meta.url);
const golden = Golden.parse(JSON.parse(readFileSync(fileURLToPath(new URL('regex-golden.frozen.json', DIR)), 'utf8')));
const rejects = Rejects.parse(
  JSON.parse(readFileSync(fileURLToPath(new URL('regex-rejects.frozen.json', DIR)), 'utf8')),
);

/** The migration path: translate, then compile the stored dialect text. Throws for a refused pattern. */
function compilePyRegex(pattern: string, context: PyRegexContext): CompiledRegex {
  const translated = translateToDialect(pattern, context);
  if (!translated.ok) throw new Error(`${translated.error.code}: ${translated.error.message}`);
  return compileRegex(translated.value.text, context);
}

type Expectation = z.infer<typeof Expected>;

/** Codes that a documented limit may raise for a pattern CPython accepts. */
const LIMIT_CODES = new Set(['INEXACT_SEMANTICS', 'UNSUPPORTED_CONSTRUCT', 'UNSUPPORTED_FLAG']);

interface Outcome {
  readonly compared: number;
  readonly mismatches: string[];
  readonly refused: string | null;
}

function show(text: string): string {
  return JSON.stringify(Array.from(text).map((c) => c.codePointAt(0)));
}

function actualOf(regex: CompiledRegex, input: string): Expectation {
  const m = regex.exec(input);
  if (m === null) return null;
  return { span: [m.start, m.end], groups: m.groups(), groupdict: m.groupdict() };
}

function compareCase(
  pattern: string,
  context: PyRegexContext,
  inputs: readonly string[],
  expected: readonly Expectation[],
): Outcome {
  const translated = translateToDialect(pattern, context);
  if (!translated.ok) return { compared: 0, mismatches: [], refused: translated.error.code };
  const regex = compileRegex(translated.value.text, context);
  const mismatches: string[] = [];
  inputs.forEach((input, index) => {
    const want = expected[index];
    const got = actualOf(regex, input);
    if (JSON.stringify(got) !== JSON.stringify(want)) {
      mismatches.push(
        `${context} ${JSON.stringify(pattern)} on ${show(input)}: node ${JSON.stringify(got)} python ${JSON.stringify(want)}`,
      );
    }
  });
  return { compared: inputs.length, mismatches, refused: null };
}

describe('PyRegex golden: corpus', () => {
  it('was generated by CPython 3 and has the documented parts', () => {
    expect(golden.meta.python).toMatch(/^3\.\d+\.\d+$/);
    const kinds = new Set(golden.cases.map((c) => c.kind));
    expect([...kinds].sort()).toEqual(['random', 'table', 'v9']);
    expect(golden.cases.filter((c) => c.kind === 'random').length).toBe(200);
    expect(
      golden.cases.filter((c) => c.kind === 'random').every((c) => c.inputs.length >= 10 && c.inputs.length <= 50),
    ).toBe(true);
    expect(rejects.rejects.length).toBeGreaterThan(100);
  });
});

describe('PyRegex golden: supported table and V9 replica', () => {
  for (const kind of ['table', 'v9'] as const) {
    it(`${kind}: every pattern translates and every result equals CPython (span, groups, groupdict)`, () => {
      const refused: string[] = [];
      const mismatches: string[] = [];
      let compared = 0;
      for (const c of golden.cases.filter((x) => x.kind === kind)) {
        const outcome = compareCase(c.pattern, c.context, c.inputs, c.expected);
        compared += outcome.compared;
        mismatches.push(...outcome.mismatches);
        if (outcome.refused !== null) refused.push(`${outcome.refused} ${c.context} ${JSON.stringify(c.pattern)}`);
      }
      expect(refused).toEqual([]);
      expect(mismatches.slice(0, 10)).toEqual([]);
      expect(mismatches.length).toBe(0);
      expect(compared).toBeGreaterThan(kind === 'table' ? 20000 : 200);
    });
  }
});

describe('PyRegex golden: random grammar', () => {
  it('translates at least 85 percent and matches CPython on every accepted pattern', () => {
    const randoms = golden.cases.filter((x) => x.kind === 'random');
    const mismatches: string[] = [];
    const badRefusals: string[] = [];
    let accepted = 0;
    let compared = 0;
    for (const c of randoms) {
      const outcome = compareCase(c.pattern, c.context, c.inputs, c.expected);
      compared += outcome.compared;
      mismatches.push(...outcome.mismatches);
      if (outcome.refused === null) accepted++;
      else if (!LIMIT_CODES.has(outcome.refused)) badRefusals.push(`${outcome.refused} ${JSON.stringify(c.pattern)}`);
    }
    expect(badRefusals).toEqual([]);
    expect(mismatches.slice(0, 10)).toEqual([]);
    expect(mismatches.length).toBe(0);
    expect(accepted / randoms.length).toBeGreaterThanOrEqual(0.85);
    expect(compared).toBeGreaterThan(5000);
  });
});

function inRanges(ranges: readonly (readonly [number, number])[]): (cp: number) => boolean {
  // ranges are sorted and disjoint: binary search
  return (cp) => {
    let lo = 0;
    let hi = ranges.length - 1;
    while (lo <= hi) {
      const mid = (lo + hi) >> 1;
      const range = ranges[mid];
      if (range === undefined) return false;
      if (cp < range[0]) hi = mid - 1;
      else if (cp > range[1]) lo = mid + 1;
      else return true;
    }
    return false;
  };
}

describe('PyRegex golden: Unicode class sweep (E7)', () => {
  const assigned = inRanges(golden.assigned);
  const FULL = new Set(['\\w', '\\d', '\\s', '.', '(?i)\\w', '(?i)\\W']);
  for (const sweep of golden.classes) {
    it(`${sweep.pattern} agrees with CPython on every code point that Python's Unicode tables assign`, () => {
      const regex = compilePyRegex(sweep.pattern, 'attempts');
      const python = inRanges(sweep.ranges);
      const step = FULL.has(sweep.pattern) ? 1 : 1 + (sweep.pattern.length % 3);
      const end = FULL.has(sweep.pattern) ? 0x110000 : 0x30000;
      const mismatches: number[] = [];
      let compared = 0;
      for (let cp = 0; cp < end; cp += step) {
        if (cp >= 0xd800 && cp <= 0xdfff) continue;
        if (!assigned(cp)) continue;
        compared++;
        if ((regex.exec(String.fromCodePoint(cp)) !== null) !== python(cp)) mismatches.push(cp);
      }
      expect(mismatches.slice(0, 20)).toEqual([]);
      expect(compared).toBeGreaterThan(FULL.has(sweep.pattern) ? 150_000 : 20_000);
    }, 120_000);
  }
});

describe('PyRegex golden: rejects', () => {
  it('refuses every row with the documented code and never accepts a refused pattern silently', () => {
    const wrong: string[] = [];
    for (const row of rejects.rejects) {
      const result = translateToDialect(row.pattern, row.context);
      if (result.ok) wrong.push(`accepted ${row.context} ${JSON.stringify(row.pattern)} (want ${row.code})`);
      else if (result.error.code !== row.code)
        wrong.push(`${result.error.code} for ${JSON.stringify(row.pattern)} (want ${row.code})`);
    }
    expect(wrong).toEqual([]);
  });

  it('reports a message and, for parse refusals, a code point position inside the pattern', () => {
    for (const row of rejects.rejects.slice(0, 40)) {
      const result = translateToDialect(row.pattern, row.context);
      if (result.ok) throw new Error(`accepted ${JSON.stringify(row.pattern)}`);
      expect(result.error.message.length).toBeGreaterThan(5);
      const position = result.error.position;
      if (position !== null) {
        expect(position).toBeGreaterThanOrEqual(0);
        expect(position).toBeLessThanOrEqual(Array.from(row.pattern).length);
      }
    }
  });

  it('lists CPython errors for the rows that CPython refuses itself', () => {
    const python = rejects.rejects.filter((r) => r.pythonError !== null).length;
    const accepted = rejects.rejects.filter((r) => r.pythonError === null).length;
    expect(python).toBeGreaterThan(60);
    expect(accepted).toBeGreaterThan(20);
  });
});

import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { basename, dirname, join } from 'node:path';

import { afterAll, describe, expect, it } from 'vitest';

import { FIXTURE_MARKER_TEXT, makeTempDir, useTempDirs, writeFixtureMarker } from './temp.ts';

describe('makeTempDir', () => {
  it('creates mcs-<purpose>-<random> under the OS temp folder', () => {
    const dir = makeTempDir('unit');
    try {
      expect(dirname(dir.path)).toBe(tmpdir());
      expect(basename(dir.path)).toMatch(/^mcs-unit-[A-Za-z0-9]{6}$/);
      expect(existsSync(dir.path)).toBe(true);
    } finally {
      dir.remove();
    }
  });

  it('writes the FIXTURE.md marker', () => {
    const dir = makeTempDir('marker');
    try {
      expect(readFileSync(join(dir.path, 'FIXTURE.md'), 'utf8')).toBe(FIXTURE_MARKER_TEXT);
      expect(FIXTURE_MARKER_TEXT).toContain('Synthetic test data generated by @mcs/testkit. Not real data.');
    } finally {
      dir.remove();
    }
  });

  it('gives every call its own folder', () => {
    const a = makeTempDir('twin');
    const b = makeTempDir('twin');
    try {
      expect(a.path).not.toBe(b.path);
    } finally {
      a.remove();
      b.remove();
    }
  });

  it('remove deletes the tree and may be called twice', () => {
    const dir = makeTempDir('remove');
    writeFileSync(join(dir.path, 'a.txt'), 'x');
    dir.remove();
    expect(existsSync(dir.path)).toBe(false);
    expect(() => {
      dir.remove();
    }).not.toThrow();
  });

  it('accepts underscores and dots in a purpose', () => {
    for (const good of ['iso_two', 'a.b', 'v1.2_x-y']) {
      const dir = makeTempDir(good);
      try {
        expect(basename(dir.path).startsWith(`mcs-${good}-`), good).toBe(true);
      } finally {
        dir.remove();
      }
    }
  });

  it('rejects a purpose that could leave the temp folder or is empty', () => {
    for (const bad of ['', '..', 'a..b', '../x', 'a/b', 'a\\b', 'a b', 'x'.repeat(33)]) {
      expect(() => makeTempDir(bad), bad).toThrow(RangeError);
    }
  });
});

describe('writeFixtureMarker', () => {
  it('adds the marker to an existing folder and never overwrites one', () => {
    const dir = makeTempDir('marker2');
    try {
      writeFileSync(join(dir.path, 'FIXTURE.md'), 'custom');
      writeFixtureMarker(dir.path);
      expect(readFileSync(join(dir.path, 'FIXTURE.md'), 'utf8')).toBe('custom');
    } finally {
      dir.remove();
    }
  });
});

describe('useTempDirs', () => {
  const make = useTempDirs();
  const made: string[] = [];

  it('hands out marked temp folders', () => {
    const dir = make('hook');
    made.push(dir.path);
    expect(existsSync(join(dir.path, 'FIXTURE.md'))).toBe(true);
  });

  it('hands out a different folder to every caller', () => {
    const a = make('hook');
    const b = make('hook');
    made.push(a.path, b.path);
    expect(a.path).not.toBe(b.path);
  });

  afterAll(() => {
    // afterAll runs after the last afterEach, whatever the order of the tests above
    expect(made).toHaveLength(3);
    for (const path of made) expect(existsSync(path), path).toBe(false);
  });
});

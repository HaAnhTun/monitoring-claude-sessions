// Temp folders of the fixture library (05 4.4): every root is `mcs-<purpose>-<random>` and carries a FIXTURE.md marker.
import { existsSync, mkdirSync, mkdtempSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';

import { afterEach } from 'vitest';

export interface TempDir {
  readonly path: string;
  remove(): void;
}

/** Content of the `FIXTURE.md` marker of every temp root. */
export const FIXTURE_MARKER_TEXT = 'Synthetic test data generated by @mcs/testkit. Not real data.\n';

const PURPOSE_RE = /^[A-Za-z0-9._-]{1,32}$/;

/** Writes `FIXTURE.md` into `dir` (created when missing) unless a marker is already there. */
export function writeFixtureMarker(dir: string): void {
  mkdirSync(dir, { recursive: true });
  const marker = join(dir, 'FIXTURE.md');
  if (!existsSync(marker)) writeFileSync(marker, FIXTURE_MARKER_TEXT);
}

/** `mkdtemp` under the OS temp folder, with the marker. On Windows SQLite and just-killed processes hold locks for tens of ms, on a loaded machine for seconds (EPERM, EBUSY): the removal retries for about 5 s. */
export function makeTempDir(purpose: string): TempDir {
  if (!PURPOSE_RE.test(purpose) || purpose.includes('..')) {
    throw new RangeError(`makeTempDir: purpose must match ${String(PURPOSE_RE)}, got '${purpose}' (no '..')`);
  }
  const path = mkdtempSync(join(tmpdir(), `mcs-${purpose}-`));
  writeFixtureMarker(path);
  return {
    path,
    remove: () => {
      rmSync(path, { recursive: true, force: true, maxRetries: 10, retryDelay: 100 });
    },
  };
}

/** Registers an `afterEach` that removes every folder the returned factory made during the test. */
export function useTempDirs(): (purpose: string) => TempDir {
  let live: TempDir[] = [];
  afterEach(() => {
    const dirs = live;
    live = [];
    for (const dir of dirs) dir.remove();
  });
  return (purpose) => {
    const dir = makeTempDir(purpose);
    live.push(dir);
    return dir;
  };
}

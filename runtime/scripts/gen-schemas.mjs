// The one JSON Schema generator (01 section 2.9, 03 section 13 item 4, registry C45). Zero dependencies of its own: it reads
// the Zod schemas of the built `@mcs/shared` and writes
//   <skill>/schemas/{config,runtime,instance,state,backup-manifest,cli-envelope,diagnostics}.v1.schema.json   (01 2.9)
//   <skill>/schemas/api/<routeId>.{params,query,body,response}.schema.json and schemas/api/stream.schema.json (03 13)
//   <skill>/schemas/export/<type>.schema.json                                                                 (03 11.1)
//   <skill>/docs/api/reference.md                                                                             (03 13)
// Usage:  node scripts/gen-schemas.mjs [--check] [--no-pending] [--root <skill folder>]
//   (none)         regenerate the committed files (`npm run schemas`); needs `npm run build` first because it imports the
//                  built `@mcs/shared` (run with `node --conditions=@mcs/source` to read the TypeScript sources instead)
//   --check        regenerate into a temporary folder and compare byte for byte with the committed files, exit 1 on drift
//                  (`npm run schemas:check`)
//   --no-pending   also exit 1 when a schema whose Zod source is not exported yet is skipped (the Phase 6 gate)
//   --root <dir>   the folder that holds `schemas/` and `docs/` (default: the skill root; tests use a copy)
// Exit codes: 0 done / identical, 1 drift or error, 2 usage.
import { mkdirSync, mkdtempSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join, relative, resolve, sep } from 'node:path';
import { pathToFileURL } from 'node:url';
// `zod` is a dependency of `@mcs/shared`, hoisted to the workspace root; the script must use the same copy as the schemas.

// ---- building ---------------------------------------------------------------------------------------------------------

/** Returns the schema as a plain JSON-ready object with `$schema`, `$id`, a generated marker, title and description first. */
function build(schema, io, file, title, description) {
  const json = z.toJSONSchema(schema, { target: DRAFT, io });
  const { $schema, title: ownTitle, description: ownDescription, ...rest } = json;
  return {
    $schema,
    $id: `${SCHEMA_ID_PREFIX}${file}`,
    $comment: GENERATED_MARKER,
    title: ownTitle ?? title,
    description: ownDescription === undefined ? description : `${description} ${ownDescription}`,
    ...rest,
  };
}

const text = (value) => `${JSON.stringify(value, null, 2)}\n`;

function isSchema(value) {
  return typeof value === 'object' && value !== null && typeof value.safeParse === 'function';
}

/** The parameters of an input schema as `[name, required]`, read from its JSON Schema. */
function parameterList(json) {
  const properties =
    typeof json.properties === 'object' && json.properties !== null ? Object.keys(json.properties) : [];
  const required = new Set(Array.isArray(json.required) ? json.required : []);
  return properties.map((name) => [name, required.has(name)]);
}

/**
 * Generates every file in memory. `shared` is the module namespace of `@mcs/shared`. Returns the files keyed by their path
 * relative to the skill root (forward slashes) and the schemas that were skipped because their source is not exported yet.
 */
export function generateAll(shared) {
  /** @type {Map<string, string>} */
  const files = new Map();
  /** @type {string[]} */
  const pending = [];

  for (const entry of CONFIG_SCHEMAS) {
    const schema = shared[entry.source];
    if (!isSchema(schema)) {
      pending.push(`schemas/${entry.file} (${entry.source} is not exported by @mcs/shared yet)`);
      continue;
    }
    files.set(`schemas/${entry.file}`, text(build(schema, entry.io, entry.file, entry.title, entry.description)));
  }

  // ---- API: one file per non-null route part (03 section 13 item 4)
  const routes = Object.values(shared.routes ?? {});
  const routeDocs = [];
  for (const route of routes) {
    const doc = { route, parts: {} };
    for (const [part, io] of [
      ['params', 'input'],
      ['query', 'input'],
      ['body', 'input'],
      ['response', 'output'],
    ]) {
      const schema = route[part];
      if (schema === null || schema === undefined) continue;
      const file = `api/${route.id}.${part}.schema.json`;
      const json = build(
        schema,
        io,
        file,
        `${route.id} ${part}`,
        `${route.method} ${route.path}: ${route.summary} (${part}; generated from the route registry of @mcs/shared, docs/design/03-data-api-realtime.md section 13).`,
      );
      files.set(`schemas/${file}`, text(json));
      doc.parts[part] = { file, json };
    }
    routeDocs.push(doc);
  }

  // ---- the SSE stream: one document holding the four event payloads
  const eventSchemas = shared.StreamEventSchemas;
  const streamEvents = [];
  if (typeof eventSchemas === 'object' && eventSchemas !== null) {
    const defs = {};
    for (const [name, schema] of Object.entries(eventSchemas)) {
      const inner = { ...z.toJSONSchema(schema, { target: DRAFT, io: 'output' }) };
      delete inner.$schema;
      defs[name] = inner;
      streamEvents.push(name);
    }
    const stream = {
      $schema: 'https://json-schema.org/draft/2020-12/schema',
      $id: `${SCHEMA_ID_PREFIX}api/stream.schema.json`,
      $comment: GENERATED_MARKER,
      title: 'GET /api/v3/stream events',
      description:
        'The data of each server-sent event name: hello, change, heartbeat and reset (docs/design/03-data-api-realtime.md section 9).',
      oneOf: streamEvents.map((name) => ({ $ref: `#/$defs/${name}` })),
      $defs: defs,
    };
    files.set('schemas/api/stream.schema.json', text(stream));
  } else {
    pending.push('schemas/api/stream.schema.json (StreamEventSchemas is not exported by @mcs/shared yet)');
  }

  // ---- the export format: one file per line type
  const exportTypes = [];
  const lineSchemas = shared.ExportLineSchemas;
  if (typeof lineSchemas === 'object' && lineSchemas !== null) {
    for (const [type, schema] of Object.entries(lineSchemas)) {
      const file = `export/${type}.schema.json`;
      files.set(
        `schemas/${file}`,
        text(
          build(
            schema,
            'output',
            file,
            `mcs.export/1 line "${type}"`,
            `One line of type "${type}" of the JSONL export (docs/design/03-data-api-realtime.md section 11.1).`,
          ),
        ),
      );
      exportTypes.push(type);
    }
  } else {
    pending.push('schemas/export/*.schema.json (ExportLineSchemas is not exported by @mcs/shared yet)');
  }

  files.set(REFERENCE_FILE, referenceMarkdown(routeDocs, shared.COMMON_ERROR_CODES ?? [], streamEvents, exportTypes));
  return { files, pending };
}

// ---- docs/api/reference.md ----------------------------------------------------------------------------------------------

/** Keeps a table cell on one line. */
const cell = (value) => String(value).replaceAll('|', '/').replaceAll(/\s+/g, ' ');

function referenceMarkdown(routeDocs, commonErrors, streamEvents, exportTypes) {
  const link = (file) => `[\`${file}\`](../../schemas/${file})`;
  const lines = [
    '<!-- Generated by runtime/scripts/gen-schemas.mjs (npm run schemas); generated; do not edit. -->',
    '',
    '# HTTP API reference (v3)',
    '',
    'Generated from the route registry of `@mcs/shared` (`packages/shared/src/api/routes.ts`). Every request part and every',
    'response has a JSON Schema (draft 2020-12) under `schemas/api/`; inputs are described as received (`io: input`), responses as',
    'sent. The contract rules (versioning, ids, times, pagination, errors) are in `docs/design/03-data-api-realtime.md`.',
    '',
    '## Routes',
    '',
    '| Route id | Method | Path | Summary |',
    '|---|---|---|---|',
    ...routeDocs.map(
      ({ route }) =>
        `| [\`${route.id}\`](#${route.id.toLowerCase()}) | ${route.method} | \`${route.path}\` | ${cell(route.summary)} |`,
    ),
    '',
    '## Errors every route can answer',
    '',
    commonErrors.length === 0 ? 'None listed.' : commonErrors.map((code) => `\`${code}\``).join(', '),
    '',
  ];
  for (const { route, parts } of routeDocs) {
    lines.push(`## ${route.id}`, '', `\`${route.method} ${route.path}\``, '', route.summary, '');
    lines.push(`- Success: ${route.successStatus}${route.contentType === null ? '' : ` \`${route.contentType}\``}`);
    for (const [part, label] of [
      ['params', 'Path parameters'],
      ['query', 'Query parameters'],
      ['body', 'Body'],
    ]) {
      const entry = parts[part];
      if (entry === undefined) continue;
      const names = parameterList(entry.json);
      const list =
        names.length === 0
          ? ''
          : `: ${names.map(([name, required]) => `\`${name}\`${required ? ' (required)' : ''}`).join(', ')}`;
      lines.push(`- ${label}${list} (${link(entry.file)})`);
    }
    if (parts['response'] !== undefined) lines.push(`- Response: ${link(parts['response'].file)}`);
    lines.push(
      `- Specific errors: ${route.errors.length === 0 ? 'none' : route.errors.map((code) => `\`${code}\``).join(', ')}`,
      '',
    );
  }
  lines.push('## Stream', '');
  lines.push(
    streamEvents.length === 0
      ? 'Not generated yet.'
      : `Event names: ${streamEvents.map((name) => `\`${name}\``).join(', ')}. Schemas: ${link('api/stream.schema.json')}.`,
    '',
    '## Export lines',
    '',
  );
  lines.push(
    exportTypes.length === 0
      ? 'Not generated yet.'
      : exportTypes.map((type) => `- \`${type}\`: ${link(`export/${type}.schema.json`)}`).join('\n'),
    '',
  );
  return lines.join('\n');
}

// ---- files --------------------------------------------------------------------------------------------------------------

/** Writes `files` below `root`, creating folders. */
export function writeFiles(files, root) {
  for (const [path, content] of files) {
    const target = join(root, ...path.split('/'));
    mkdirSync(dirname(target), { recursive: true });
    writeFileSync(target, content);
  }
}

function* walk(dir) {
  let entries;
  try {
    entries = readdirSync(dir, { withFileTypes: true });
  } catch {
    return;
  }
  for (const entry of entries) {
    const full = join(dir, entry.name);
    if (entry.isDirectory()) yield* walk(full);
    else yield full;
  }
}

function readOptional(file) {
  try {
    return readFileSync(file, 'utf8');
  } catch {
    return null;
  }
}

/**
 * Compares generated `files` with the committed ones below `root`. Reports a changed file, a missing one and a committed
 * `schemas/**.schema.json` that the generator no longer produces.
 */
export function compareFiles(files, root) {
  const drift = [];
  for (const [path, content] of files) {
    const committed = readOptional(join(root, ...path.split('/')));
    if (committed === null) drift.push(`missing: ${path}`);
    else if (committed !== content) drift.push(`changed: ${path}`);
  }
  for (const file of walk(join(root, 'schemas'))) {
    const rel = relative(root, file).split(sep).join('/');
    if (rel.endsWith('.schema.json') && !files.has(rel)) drift.push(`stale: ${rel}`);
  }
  return drift.sort();
}

// ---- CLI ----------------------------------------------------------------------------------------------------------------

function parseArguments(argv) {
  const options = { check: false, noPending: false, root: resolve(RUNTIME_ROOT, '..') };
  for (let i = 0; i < argv.length; i += 1) {
    const arg = argv[i];
    if (arg === '--check') options.check = true;
    else if (arg === '--no-pending') options.noPending = true;
    else if (arg === '--root' && argv[i + 1] !== undefined) {
      options.root = resolve(argv[i + 1]);
      i += 1;
    } else return null;
  }
  return options;
}

async function main(argv) {
  const options = parseArguments(argv);
  if (options === null) {
    console.error('usage: node scripts/gen-schemas.mjs [--check] [--no-pending] [--root <skill folder>]');
    return 2;
  }
  let shared;
  try {
    shared = await import('@mcs/shared');
  } catch (error) {
    console.error(
      `gen-schemas: cannot load @mcs/shared (${error instanceof Error ? error.message : String(error)}); run \`npm run build\` first`,
    );
    return 1;
  }
  const { files, pending } = generateAll(shared);
  for (const entry of pending) console.log(`gen-schemas: pending ${entry}`);
  const pendingFailure = options.noPending && pending.length > 0;

  if (options.check) {
    const scratch = mkdtempSync(join(tmpdir(), 'mcs-schemas-'));
    try {
      writeFiles(files, scratch);
      const regenerated = new Map(
        [...files.keys()].map((path) => [path, readFileSync(join(scratch, ...path.split('/')), 'utf8')]),
      );
      const drift = compareFiles(regenerated, options.root);
      if (drift.length > 0) {
        for (const line of drift) console.error(`gen-schemas: ${line}`);
        console.error(`gen-schemas: ${drift.length} file(s) differ; run \`npm run schemas\` and commit the result`);
        return 1;
      }
      console.log(`gen-schemas: ${files.size} files identical to the committed ones (${pending.length} pending)`);
      return pendingFailure ? 1 : 0;
    } finally {
      rmSync(scratch, { recursive: true, force: true });
    }
  }

  // Drop generated files that the registry no longer produces before writing the new set.
  for (const file of walk(join(options.root, 'schemas'))) {
    const rel = relative(options.root, file).split(sep).join('/');
    if (rel.endsWith('.schema.json') && !files.has(rel)) rmSync(file, { force: true });
  }
  writeFiles(files, options.root);
  console.log(`gen-schemas: wrote ${files.size} files below ${options.root} (${pending.length} pending)`);
  return pendingFailure ? 1 : 0;
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  process.exitCode = await main(process.argv.slice(2));
}

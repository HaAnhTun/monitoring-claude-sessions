/// <reference types="node" />
// Golden test of the Python-regex translator (design 01 section 2.8, ADR 0002, plan WP-05).
// Data: <skill>/tests/legacy-parity/regex/{regex-golden.json,regex-rejects.json}, written by gen_regex_golden.py.
// Every expectation is a result CPython produced; this file only compares. The opt-in live check at the end reads a
// real config only when MCS_GOLDEN_LIVE_CONFIG is set (the lead sets it, never an agent) and prints counts only.
import { spawnSync } from 'node:child_process';
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

import { describe, expect, it } from 'vitest';
import { z } from 'zod';

import { McsError, compilePyRegex, translatePyRegex, type PyRegexContext } from '@mcs/shared';

const Meta = z.object({ python: z.string(), unicode: z.string(), seed: z.number() });
const Expected = z.union([
  z.null(),
  z.object({
    span: z.tuple([z.number(), z.number()]),
    groups: z.array(z.string().nullable()),
    groupdict: z.record(z.string(), z.string().nullable()),
  }),
]);
const Context = z.enum(['session_rule', 'attempts']);
const Golden = z.object({
  meta: Meta,
  assigned: z.array(z.tuple([z.number(), z.number()])),
  classes: z.array(z.object({ pattern: z.string(), ranges: z.array(z.tuple([z.number(), z.number()])) })),
  cases: z.array(
    z.object({
      kind: z.enum(['table', 'v9', 'random']),
      pattern: z.string(),
      context: Context,
      inputs: z.array(z.string()),
      expected: z.array(Expected),
    }),
  ),
});
const Rejects = z.object({
  meta: Meta,
  rejects: z.array(
    z.object({
      pattern: z.string(),
      context: Context,
      code: z.enum(['SYNTAX', 'UNSUPPORTED_CONSTRUCT', 'UNSUPPORTED_FLAG', 'INEXACT_SEMANTICS', 'JS_COMPILE']),
      pythonError: z.string().nullable(),
    }),
  ),
});

const DIR = new URL('../../../tests/legacy-parity/regex/', import.meta.url);
const golden = Golden.parse(JSON.parse(readFileSync(fileURLToPath(new URL('regex-golden.json', DIR)), 'utf8')));
const rejects = Rejects.parse(JSON.parse(readFileSync(fileURLToPath(new URL('regex-rejects.json', DIR)), 'utf8')));

type Expectation = z.infer<typeof Expected>;

/** Codes that a documented limit may raise for a pattern CPython accepts. */
const LIMIT_CODES = new Set(['INEXACT_SEMANTICS', 'UNSUPPORTED_CONSTRUCT', 'UNSUPPORTED_FLAG']);

interface Outcome {
  readonly compared: number;
  readonly mismatches: string[];
  readonly refused: string | null;
}

function show(text: string): string {
  return JSON.stringify(Array.from(text).map((c) => c.codePointAt(0)));
}

function actualOf(regex: ReturnType<typeof compilePyRegex>, input: string): Expectation {
  const m = regex.exec(input);
  if (m === null) return null;
  return { span: [m.start, m.end], groups: m.groups(), groupdict: m.groupdict() };
}

function compareCase(
  pattern: string,
  context: PyRegexContext,
  inputs: readonly string[],
  expected: readonly Expectation[],
): Outcome {
  const translated = translatePyRegex(pattern, context);
  if (!translated.ok) return { compared: 0, mismatches: [], refused: translated.error.code };
  const regex = compilePyRegex(pattern, context);
  const mismatches: string[] = [];
  inputs.forEach((input, index) => {
    const want = expected[index];
    const got = actualOf(regex, input);
    if (JSON.stringify(got) !== JSON.stringify(want)) {
      mismatches.push(
        `${context} ${JSON.stringify(pattern)} on ${show(input)}: node ${JSON.stringify(got)} python ${JSON.stringify(want)}`,
      );
    }
  });
  return { compared: inputs.length, mismatches, refused: null };
}

describe('PyRegex golden: corpus', () => {
  it('was generated by CPython 3 and has the documented parts', () => {
    expect(golden.meta.python).toMatch(/^3\.\d+\.\d+$/);
    const kinds = new Set(golden.cases.map((c) => c.kind));
    expect([...kinds].sort()).toEqual(['random', 'table', 'v9']);
    expect(golden.cases.filter((c) => c.kind === 'random').length).toBe(200);
    expect(
      golden.cases.filter((c) => c.kind === 'random').every((c) => c.inputs.length >= 10 && c.inputs.length <= 50),
    ).toBe(true);
    expect(rejects.rejects.length).toBeGreaterThan(100);
  });
});

describe('PyRegex golden: supported table and V9 replica', () => {
  for (const kind of ['table', 'v9'] as const) {
    it(`${kind}: every pattern translates and every result equals CPython (span, groups, groupdict)`, () => {
      const refused: string[] = [];
      const mismatches: string[] = [];
      let compared = 0;
      for (const c of golden.cases.filter((x) => x.kind === kind)) {
        const outcome = compareCase(c.pattern, c.context, c.inputs, c.expected);
        compared += outcome.compared;
        mismatches.push(...outcome.mismatches);
        if (outcome.refused !== null) refused.push(`${outcome.refused} ${c.context} ${JSON.stringify(c.pattern)}`);
      }
      expect(refused).toEqual([]);
      expect(mismatches.slice(0, 10)).toEqual([]);
      expect(mismatches.length).toBe(0);
      expect(compared).toBeGreaterThan(kind === 'table' ? 20000 : 200);
    });
  }
});

describe('PyRegex golden: random grammar', () => {
  it('translates at least 85 percent and matches CPython on every accepted pattern', () => {
    const randoms = golden.cases.filter((x) => x.kind === 'random');
    const mismatches: string[] = [];
    const badRefusals: string[] = [];
    let accepted = 0;
    let compared = 0;
    for (const c of randoms) {
      const outcome = compareCase(c.pattern, c.context, c.inputs, c.expected);
      compared += outcome.compared;
      mismatches.push(...outcome.mismatches);
      if (outcome.refused === null) accepted++;
      else if (!LIMIT_CODES.has(outcome.refused)) badRefusals.push(`${outcome.refused} ${JSON.stringify(c.pattern)}`);
    }
    expect(badRefusals).toEqual([]);
    expect(mismatches.slice(0, 10)).toEqual([]);
    expect(mismatches.length).toBe(0);
    expect(accepted / randoms.length).toBeGreaterThanOrEqual(0.85);
    expect(compared).toBeGreaterThan(5000);
  });
});

function inRanges(ranges: readonly (readonly [number, number])[]): (cp: number) => boolean {
  // ranges are sorted and disjoint: binary search
  return (cp) => {
    let lo = 0;
    let hi = ranges.length - 1;
    while (lo <= hi) {
      const mid = (lo + hi) >> 1;
      const range = ranges[mid];
      if (range === undefined) return false;
      if (cp < range[0]) hi = mid - 1;
      else if (cp > range[1]) lo = mid + 1;
      else return true;
    }
    return false;
  };
}

describe('PyRegex golden: Unicode class sweep (E7)', () => {
  const assigned = inRanges(golden.assigned);
  const FULL = new Set(['\\w', '\\d', '\\s', '.', '(?i)\\w', '(?i)\\W']);
  for (const sweep of golden.classes) {
    it(`${sweep.pattern} agrees with CPython on every code point that Python's Unicode tables assign`, () => {
      const regex = compilePyRegex(sweep.pattern, 'attempts');
      const python = inRanges(sweep.ranges);
      const step = FULL.has(sweep.pattern) ? 1 : 1 + (sweep.pattern.length % 3);
      const end = FULL.has(sweep.pattern) ? 0x110000 : 0x30000;
      const mismatches: number[] = [];
      let compared = 0;
      for (let cp = 0; cp < end; cp += step) {
        if (cp >= 0xd800 && cp <= 0xdfff) continue;
        if (!assigned(cp)) continue;
        compared++;
        if ((regex.exec(String.fromCodePoint(cp)) !== null) !== python(cp)) mismatches.push(cp);
      }
      expect(mismatches.slice(0, 20)).toEqual([]);
      expect(compared).toBeGreaterThan(FULL.has(sweep.pattern) ? 150_000 : 20_000);
    }, 120_000);
  }
});

describe('PyRegex golden: rejects', () => {
  it('refuses every row with the documented code and never accepts a refused pattern silently', () => {
    const wrong: string[] = [];
    for (const row of rejects.rejects) {
      const result = translatePyRegex(row.pattern, row.context);
      if (result.ok) wrong.push(`accepted ${row.context} ${JSON.stringify(row.pattern)} (want ${row.code})`);
      else if (result.error.code !== row.code)
        wrong.push(`${result.error.code} for ${JSON.stringify(row.pattern)} (want ${row.code})`);
      expect(() => compilePyRegex(row.pattern, row.context), JSON.stringify(row.pattern)).toThrow(McsError);
    }
    expect(wrong).toEqual([]);
  });

  it('reports REGEX_UNSUPPORTED with the construct code and a position', () => {
    for (const row of rejects.rejects.slice(0, 40)) {
      try {
        compilePyRegex(row.pattern, row.context);
        expect.unreachable(`compiled ${JSON.stringify(row.pattern)}`);
      } catch (error) {
        if (!(error instanceof McsError)) throw error;
        expect(error.code).toBe('REGEX_UNSUPPORTED');
        expect(error.details?.['code']).toBe(row.code);
        expect(error.message.length).toBeGreaterThan(5);
      }
    }
  });

  it('lists CPython errors for the rows that CPython refuses itself', () => {
    const python = rejects.rejects.filter((r) => r.pythonError !== null).length;
    const accepted = rejects.rejects.filter((r) => r.pythonError === null).length;
    expect(python).toBeGreaterThan(60);
    expect(accepted).toBeGreaterThan(20);
  });
});

// ---- opt-in differential run on a real config (prints counts only, commits nothing) ------------------------------
const LIVE_SCRIPT = [
  'import json, re, sys',
  'jobs = json.load(sys.stdin)',
  'out = []',
  'for job in jobs:',
  '    flags = re.S if job["context"] == "session_rule" else 0',
  '    try:',
  '        compiled = re.compile(job["pattern"], flags)',
  '    except re.error:',
  '        out.append(None)',
  '        continue',
  '    rows = []',
  '    for text in job["inputs"]:',
  '        m = compiled.search(text) if job["context"] == "session_rule" else compiled.match(text)',
  '        rows.append(None if m is None else {"span": [m.start(), m.end()], "groups": list(m.groups()), "groupdict": m.groupdict()})',
  '    out.append(rows)',
  'json.dump(out, sys.stdout)',
].join('\n');

const LIVE_INPUTS = [
  'please run the job now and report PART=AB12 afterwards',
  '2026-01-02 03:04:05 JOB A1 BEGIN try 1 model alpha effort high',
  '2026-01-02 03:04:05 JOB A1 END code=0 state=DONE',
  'first line' + String.fromCharCode(10) + 'second line',
  '',
  'x'.repeat(50),
];

interface LiveJob {
  readonly pattern: string;
  readonly context: PyRegexContext;
  readonly inputs: readonly string[];
}

interface LiveReport {
  readonly patterns: number;
  readonly comparisons: number;
  readonly mismatches: number;
  readonly refused: number;
  readonly pythonErrors: number;
}

function findPython(): string | null {
  for (const candidate of ['python', 'python3']) {
    const probe = spawnSync(candidate, ['-B', '-c', 'print(1)'], {
      encoding: 'utf8',
      env: { ...process.env, PYTHONDONTWRITEBYTECODE: '1' },
    });
    if (probe.status === 0) return candidate;
  }
  return null;
}

const LiveConfig = z.object({
  session_rules: z.array(z.object({ match: z.string() })).default([]),
  attempts: z.object({ start: z.string().optional(), end: z.string().optional() }).optional(),
});

/**
 * Probe strings derived from the pattern text itself: sets become their first member, classes a sample character,
 * quantifier and group syntax disappears. Crude on purpose: the strings only need to land near a match, CPython judges.
 */
function heuristicInputs(pattern: string): string[] {
  const BSLASH = String.fromCharCode(92);
  const samples = new Map<string, string>([
    ['d', '7'],
    ['w', 'a'],
    ['s', ' '],
    ['D', 'x'],
    ['W', '-'],
    ['S', 'x'],
  ]);
  let base = '';
  for (let i = 0; i < pattern.length; i++) {
    const ch = pattern.charAt(i);
    if (ch === BSLASH) {
      const next = pattern.charAt(i + 1);
      base += samples.get(next) ?? next;
      i += 1;
    } else if (ch === '[') {
      const close = pattern.indexOf(']', i + 2);
      const body = pattern.slice(i + 1, close < 0 ? pattern.length : close).replace(/^\^/, '');
      base += body.startsWith(BSLASH) ? (samples.get(body.charAt(1)) ?? body.charAt(1)) : body.charAt(0);
      i = close < 0 ? pattern.length : close;
    } else if (ch === '{') {
      const close = pattern.indexOf('}', i);
      if (close > 0 && /^[0-9,]*$/.test(pattern.slice(i + 1, close))) i = close;
      else base += ch;
    } else if (ch === '(' && pattern.startsWith('(?P<', i)) {
      i = pattern.indexOf('>', i);
    } else if (ch === '(' && pattern.charAt(i + 1) === '?') {
      i += 2;
    } else if (ch === '.') {
      base += 'x';
    } else if (!'()^$*+?|'.includes(ch)) {
      base += ch;
    }
  }
  const lf = String.fromCharCode(10);
  const emoji = String.fromCodePoint(0x1f600);
  return [
    base,
    base + base,
    base.toUpperCase(),
    base.toLowerCase(),
    ` ${base}`,
    `${base}${lf}`,
    `${base}${lf}${base}`,
    `${emoji}${base}`,
    `${base}${emoji}`,
    base.slice(0, Math.floor(base.length / 2)),
    base.slice(Math.floor(base.length / 2)),
    `${base} trailing text`,
    base.replace(/[a-z]/, '0'),
  ];
}

function liveJobs(configPath: string, extraInputs: readonly string[]): LiveJob[] {
  const config = LiveConfig.parse(JSON.parse(readFileSync(configPath, 'utf8')));
  const shared = [...LIVE_INPUTS, ...extraInputs];
  const jobs: LiveJob[] = config.session_rules.map((rule) => ({
    pattern: rule.match,
    context: 'session_rule',
    inputs: [...shared, ...heuristicInputs(rule.match)],
  }));
  for (const pattern of [config.attempts?.start, config.attempts?.end]) {
    if (pattern !== undefined)
      jobs.push({ pattern, context: 'attempts', inputs: [...shared, ...heuristicInputs(pattern)] });
  }
  return jobs;
}

function runLive(python: string, jobs: readonly LiveJob[]): LiveReport {
  const run = spawnSync(python, ['-B', '-c', LIVE_SCRIPT], {
    input: JSON.stringify(jobs),
    encoding: 'utf8',
    maxBuffer: 64 * 1024 * 1024,
    env: { ...process.env, PYTHONDONTWRITEBYTECODE: '1' },
  });
  if (run.status !== 0) throw new Error('the Python side of the live check failed');
  const results = z.array(z.array(Expected).nullable()).parse(JSON.parse(run.stdout));
  let comparisons = 0;
  let mismatches = 0;
  let refused = 0;
  let pythonErrors = 0;
  jobs.forEach((job, index) => {
    const rows = results[index];
    if (rows === null || rows === undefined) {
      pythonErrors++;
      return;
    }
    const outcome = compareCase(job.pattern, job.context, job.inputs, rows);
    comparisons += outcome.compared;
    mismatches += outcome.mismatches.length;
    if (outcome.refused !== null) refused++;
  });
  return { patterns: jobs.length, comparisons, mismatches, refused, pythonErrors };
}

describe('PyRegex live differential machinery (synthetic config)', () => {
  const python = findPython();
  it.skipIf(python === null)('compares a synthetic config against CPython and reports counts only', () => {
    if (python === null) return;
    const dir = mkdtempSync(join(tmpdir(), 'mcs-pyregex-'));
    try {
      const path = join(dir, 'config.json');
      writeFileSync(
        path,
        JSON.stringify({
          session_rules: [{ match: 'job[.]md.*?PART=([A-Z0-9]+)' }, { match: '(?P<verb>run|build) (?P<what>[a-z.]+)' }],
          attempts: {
            start: '^(?P<time>[0-9]{4}-[0-9]{2}-[0-9]{2} [0-9:]{8}) JOB (?P<part>[A-Z0-9]+) BEGIN',
            end: '^(?P<time>[0-9]{4}-[0-9]{2}-[0-9]{2} [0-9:]{8}) JOB (?P<part>[A-Z0-9]+) END code=(?P<exit>[0-9]+)',
          },
        }),
      );
      const report = runLive(python, liveJobs(path, []));
      expect(report.patterns).toBe(4);
      expect(report.refused).toBe(0);
      expect(report.pythonErrors).toBe(0);
      expect(report.mismatches).toBe(0);
      expect(report.comparisons).toBeGreaterThan(4 * (LIVE_INPUTS.length + 10));
    } finally {
      rmSync(dir, { recursive: true, force: true });
    }
  });

  const livePath = process.env['MCS_GOLDEN_LIVE_CONFIG'];
  it.skipIf(python === null || livePath === undefined || livePath === '')(
    'opt-in: differential run on MCS_GOLDEN_LIVE_CONFIG',
    () => {
      if (python === null || livePath === undefined) return;
      const extraPath = process.env['MCS_GOLDEN_LIVE_INPUTS'];
      const extra = extraPath === undefined || extraPath === '' ? [] : readFileSync(extraPath, 'utf8').split(/\r?\n/);
      const report = runLive(python, liveJobs(livePath, extra));
      // Counts only: never print a pattern, an input or a path of the real config.
      process.stdout.write(`pyregex live check: ${JSON.stringify(report)}\n`);
      expect(report.mismatches).toBe(0);
      expect(report.refused).toBe(0);
    },
  );
});

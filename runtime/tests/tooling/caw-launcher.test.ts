// The canonical launcher `skills/monitoring-claude-sessions/scripts/caw.mjs` and its alias `mcs.mjs` (CAW-04, design 07 sections
// 5.2 and 8.1): `caw.mjs` holds the whole launcher and exports `run(argv, { program, launcherPath })`; `mcs.mjs` is a short alias
// that calls it with the program `mcs` and the path of `caw.mjs`. This file pins what is specific to that split: the floor message
// from both entry points, the hand-over of the argv and of the canonical `launcherPath`, the exported `run` that a legacy shim
// calls, the exact import lists, the ES2020 syntax and the readers of the two launcher variables. The helpers and the real
// bundle are covered by `launcher.test.ts`.
import { execFile } from 'node:child_process';
import { mkdirSync, mkdtempSync, readFileSync, realpathSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { pathToFileURL } from 'node:url';

import { DOCUMENTED_ENV_VARS } from '@mcs/shared';
import { Linter } from 'eslint';
import { afterAll, describe, expect, it } from 'vitest';

const REPO = resolve(import.meta.dirname, '..', '..', '..');
const SKILLDIR = join(REPO, 'skills', 'monitoring-claude-sessions');
const CAW = join(SKILLDIR, 'scripts', 'caw.mjs');
const MCS = join(SKILLDIR, 'scripts', 'mcs.mjs');
const CAW_RELATIVE = 'skills/monitoring-claude-sessions/scripts/caw.mjs';

interface BenchTarget {
  DEFAULT_LAUNCHER: string;
}
interface DockerPlan {
  containerScript(options: { target: string; quick: boolean; bundle: boolean }): string;
}
const benchTarget = (await import(
  pathToFileURL(join(REPO, 'runtime', 'bench', 'lib', 'target.mjs')).href
)) as BenchTarget;
const dockerPlan = (await import(
  pathToFileURL(join(REPO, 'runtime', 'scripts', 'docker-posix-plan.mjs')).href
)) as DockerPlan;

const temps: string[] = [];
afterAll(() => {
  for (const dir of temps) rmSync(dir, { recursive: true, force: true, maxRetries: 5, retryDelay: 100 });
});

/** A fresh temp folder by its real path (the launcher sees its own path resolved, e.g. no Windows 8.3 short names). */
function tempRoot(label: string): string {
  const dir = realpathSync.native(mkdtempSync(join(tmpdir(), `caw-launcher-${label}-`)));
  temps.push(dir);
  writeFileSync(
    join(dir, 'FIXTURE.md'),
    'Synthetic test data generated by tests/tooling/caw-launcher.test.ts. Not real data.\n',
  );
  return dir;
}

function write(path: string, text: string): void {
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, text);
}

/** Records its arguments as JSON into the file named by `FAKE_RECORD` and returns `code`. */
function fakeCli(code: number): string {
  return [
    "import { writeFileSync } from 'node:fs';",
    'export async function main(argv, paths) {',
    '  writeFileSync(process.env.FAKE_RECORD, JSON.stringify({ argv, paths }));',
    `  return ${String(code)};`,
    '}',
    '',
  ].join('\n');
}

interface Run {
  code: number;
  stdout: string;
  stderr: string;
}

function runNode(args: readonly string[], env: Record<string, string>, cwd: string): Promise<Run> {
  return new Promise((done) => {
    execFile(
      process.execPath,
      [...args],
      { cwd, env, windowsHide: true, timeout: 60_000, encoding: 'utf8' },
      (error, stdout, stderr) => {
        const code = error === null ? 0 : typeof error.code === 'number' ? error.code : -1;
        done({ code, stdout, stderr });
      },
    );
  });
}

/** The parent's environment without any `CAW_*`, `MCS_*` or `CLAUDE_*` variable, plus `extra`. */
function cleanEnv(extra: Record<string, string> = {}): Record<string, string> {
  const env: Record<string, string> = {};
  for (const [key, value] of Object.entries(process.env)) {
    if (value !== undefined && !/^(CAW_|MCS_|CLAUDE_)/i.test(key)) env[key] = value;
  }
  return { ...env, MCS_HOOK_DISABLE: '1', ...extra };
}

interface FakeSkill {
  skillDir: string;
  caw: string;
  mcs: string;
}

/** `<root>/<folder>/scripts/{caw,mcs}.mjs` (the real files) with a fake bundle. */
function fakeSkill(root: string, bundle: string, folder = 'repo/skills/mcs'): FakeSkill {
  const skillDir = join(root, ...folder.split('/'));
  const caw = join(skillDir, 'scripts', 'caw.mjs');
  const mcs = join(skillDir, 'scripts', 'mcs.mjs');
  write(caw, readFileSync(CAW, 'utf8'));
  write(mcs, readFileSync(MCS, 'utf8'));
  write(join(skillDir, 'bundle', 'mcs-cli.mjs'), bundle);
  write(join(skillDir, 'bundle', '.mcs-build.json'), '{"schemaVersion":1,"runtimeVersion":"8.8.8"}\n');
  return { skillDir, caw, mcs };
}

interface Recorded {
  argv: string[];
  paths: { launcherPath: string; skillDir: string; runtimeDir: string; program: string };
}

function recordedOf(file: string): Recorded {
  return JSON.parse(readFileSync(file, 'utf8')) as Recorded;
}

/** Static `import ... from 'x'` specifiers of a module, in source order. */
function staticImports(source: string): string[] {
  return [...source.matchAll(/^\s*import\s[^'"]*['"]([^'"]+)['"]/gm)].map((m) => m[1] ?? '');
}

describe('the two entry points', () => {
  it('both files exist; importing either has no side effect; caw.mjs exports run and the helpers, the alias nothing', async () => {
    const caw = (await import(pathToFileURL(CAW).href)) as Record<string, unknown>;
    const mcs = (await import(pathToFileURL(MCS).href)) as Record<string, unknown>;
    expect(typeof caw['run']).toBe('function');
    for (const name of [
      'NODE_FLOOR',
      'meetsNodeFloor',
      'floorMessage',
      'noRuntimeMessage',
      'chooseMode',
      'versionLine',
      'isVersionFastPath',
      'launcherPaths',
      'isEntry',
    ]) {
      expect(caw, name).toHaveProperty(name);
    }
    expect(Object.keys(mcs)).toEqual([]);
    expect(process.exitCode).toBeUndefined();
  });

  it('prints the floor message and exits 1 before it imports anything, from caw.mjs and from the alias alike', async () => {
    const root = tempRoot('floor');
    const fake = fakeSkill(root, "throw new Error('bundle import failed');\n");
    const preload = join(root, 'old-node.mjs');
    write(
      preload,
      "Object.defineProperty(process, 'versions', { value: { ...process.versions, node: '20.11.1' } });\n",
    );
    const expected = {
      code: 1,
      stdout: '',
      stderr: 'ERROR: Node >= 22.22.0 is required (found 20.11.1); install the Node 24 LTS\n',
    };
    for (const entry of [fake.caw, fake.mcs]) {
      const old = await runNode(['--import', pathToFileURL(preload).href, entry, 'status'], cleanEnv(), root);
      expect(old, entry).toEqual(expected);
    }
  });

  it('hands the argv over verbatim and the canonical caw.mjs path to the CLI, with the program of the entry point', async () => {
    const root = tempRoot('handover');
    const fake = fakeSkill(root, fakeCli(5), 'skill folder ñé ü/monitoring-claude-sessions');
    const argv = ['status', '--json', '--name=a b', '', 'ünï côdé', '--', '-x'];
    for (const [entry, program] of [
      [fake.caw, 'caw'],
      [fake.mcs, 'mcs'],
    ] as const) {
      const record = join(root, `record-${program}.json`);
      const run = await runNode([entry, ...argv], cleanEnv({ FAKE_RECORD: record }), root);
      expect(run.stderr, entry).toBe('');
      expect(run.code, entry).toBe(5);
      expect(recordedOf(record), entry).toEqual({
        argv,
        paths: {
          launcherPath: fake.caw,
          skillDir: fake.skillDir,
          runtimeDir: join(fake.skillDir, 'bundle'),
          program,
        },
      });
    }
  });

  it('answers the version fast path the same way from both entry points without loading the bundle', async () => {
    const root = tempRoot('version');
    const fake = fakeSkill(root, "throw new Error('must not load');\n");
    for (const entry of [fake.caw, fake.mcs]) {
      for (const args of [['--version'], ['version', '--short']]) {
        expect(await runNode([entry, ...args], cleanEnv(), root), `${entry} ${args.join(' ')}`).toEqual({
          code: 0,
          stdout: 'mcs 8.8.8\n',
          stderr: '',
        });
      }
    }
  });
});

describe('the exported run', () => {
  /** A shim in the style of the installer's legacy launcher: it imports `run` from `caw.mjs` and calls it. */
  function writeShim(root: string, callText: string): string {
    const shim = join(root, 'shim.mjs');
    write(
      shim,
      [
        "import { pathToFileURL } from 'node:url';",
        'const { run } = await import(pathToFileURL(process.env.SHIM_LAUNCHER).href);',
        'let threw = false;',
        `try { await ${callText}; } catch { threw = true; }`,
        "process.stdout.write(JSON.stringify({ threw, exitCode: process.exitCode ?? null }) + '\\n');",
        '',
      ].join('\n'),
    );
    return shim;
  }

  it('takes { program, launcherPath }, hands both to the CLI and sets the exit code', async () => {
    const root = tempRoot('run');
    const fake = fakeSkill(root, fakeCli(6));
    const record = join(root, 'record.json');
    const shim = writeShim(
      root,
      'run(["inspect", "--task", "demo"], { program: "mcs", launcherPath: process.env.SHIM_LAUNCHER })',
    );
    const result = await runNode([shim], cleanEnv({ FAKE_RECORD: record, SHIM_LAUNCHER: fake.caw }), root);
    expect(result.stderr).toBe('');
    expect(JSON.parse(result.stdout.trim())).toEqual({ threw: false, exitCode: 6 });
    expect(recordedOf(record)).toEqual({
      argv: ['inspect', '--task', 'demo'],
      paths: {
        launcherPath: fake.caw,
        skillDir: fake.skillDir,
        runtimeDir: join(fake.skillDir, 'bundle'),
        program: 'mcs',
      },
    });
  });

  it('defaults to the program caw and to its own path, and reads any other program name as caw', async () => {
    const root = tempRoot('defaults');
    const fake = fakeSkill(root, fakeCli(0));
    const record = join(root, 'record.json');
    const env = cleanEnv({ FAKE_RECORD: record, SHIM_LAUNCHER: fake.caw });
    expect((await runNode([writeShim(root, 'run(["help"])')], env, root)).stderr).toBe('');
    expect(recordedOf(record).paths).toEqual({
      launcherPath: fake.caw,
      skillDir: fake.skillDir,
      runtimeDir: join(fake.skillDir, 'bundle'),
      program: 'caw',
    });
    const other = writeShim(root, 'run(["help"], { program: "other", launcherPath: process.env.SHIM_LAUNCHER })');
    expect((await runNode([other], env, root)).stderr).toBe('');
    expect(recordedOf(record).paths.program).toBe('caw');
  });

  it('never throws: an internal error becomes the message on stderr and exit code 1', async () => {
    const root = tempRoot('never-throws');
    const fake = fakeSkill(root, "throw new Error('bundle import failed');\n");
    const shim = writeShim(root, 'run(["status"], { program: "mcs", launcherPath: process.env.SHIM_LAUNCHER })');
    const result = await runNode([shim], cleanEnv({ SHIM_LAUNCHER: fake.caw }), root);
    expect(result.stderr).toBe('ERROR: internal launcher error: bundle import failed\n');
    expect(JSON.parse(result.stdout.trim())).toEqual({ threw: false, exitCode: 1 });
  });
});

describe('static rules of the two files', () => {
  const cawSource = readFileSync(CAW, 'utf8');
  const mcsSource = readFileSync(MCS, 'utf8');

  it('caw.mjs imports exactly node:fs, node:path and node:url; the alias adds only ./caw.mjs', () => {
    expect(staticImports(cawSource).sort()).toEqual(['node:fs', 'node:path', 'node:url']);
    expect(staticImports(mcsSource).sort()).toEqual(['./caw.mjs', 'node:path', 'node:url']);
  });

  it('keeps the alias short and free of any environment variable, process spawn or logic of its own', () => {
    expect(mcsSource.trimEnd().split('\n').length).toBeLessThanOrEqual(30);
    const code = mcsSource.replace(/\/\*[\s\S]*?\*\/|^\s*\/\/.*$/gm, '');
    expect(code).not.toMatch(/\b(?:MCS|CAW)_[A-Z]/);
    expect(code).not.toContain('process.env');
    for (const word of ['child_process', 'spawn', 'execFile', 'require(', 'readFileSync']) {
      expect(code, word).not.toContain(word);
    }
    expect(code).toContain("program: 'mcs'");
    expect(code).toContain("'caw.mjs'");
  });

  it('both files pass node --check', async () => {
    for (const file of [CAW, MCS]) {
      expect(await runNode(['--check', file], cleanEnv(), REPO), file).toEqual({ code: 0, stdout: '', stderr: '' });
    }
  });

  it('both files use no syntax newer than ES2020 (no top-level await, no logical assignment)', () => {
    const parse = (code: string) =>
      new Linter()
        .verify(code, [{ languageOptions: { ecmaVersion: 2020, sourceType: 'module' } }])
        .filter((m) => m.fatal);
    expect(parse(cawSource)).toEqual([]);
    expect(parse(mcsSource)).toEqual([]);
    // negative controls: ES2022 top-level await and ES2021 logical assignment are rejected
    expect(parse('await Promise.resolve(1);\n')).toHaveLength(1);
    expect(parse('let a = 0;\na ||= 1;\n')).toHaveLength(1);
  });

  it('names caw.mjs, not the alias, as the reader of MCS_LAUNCHER_MODE and MCS_DEBUG, and caw.mjs mentions both', () => {
    for (const name of ['MCS_LAUNCHER_MODE', 'MCS_DEBUG']) {
      const entry = DOCUMENTED_ENV_VARS.find((v) => v.name === name);
      expect(entry, name).toBeDefined();
      expect(entry?.readers, name).toContain(CAW_RELATIVE);
      expect(entry?.readers, name).not.toContain(CAW_RELATIVE.replace('caw.mjs', 'mcs.mjs'));
      expect(cawSource, name).toContain(name);
    }
  });
});

describe('the repository tooling that names the launcher', () => {
  it('the benchmark target defaults to the canonical caw.mjs', () => {
    expect(benchTarget.DEFAULT_LAUNCHER).toBe(CAW);
  });

  it('the container floor check runs caw.mjs, from the checkout layout and from a bare scripts folder', () => {
    const script = dockerPlan.containerScript({ target: 'floor', quick: true, bundle: false });
    expect(script).toContain('launcher=skills/monitoring-claude-sessions/scripts/caw.mjs');
    expect(script).toContain('launcher=scripts/caw.mjs');
    expect(script).not.toContain('mcs.mjs');
  });
});

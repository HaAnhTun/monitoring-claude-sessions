// The third-party notices of the bundle (ADR 0063 item 6): the allow list, a deterministic LF-only text without dates, the
// marker line for a package without a licence file, the production closure of a synthetic lockfile (dev packages excluded,
// nested `node_modules` resolved), the embedded-notice table for code a package vendors inside its own dist file, and the notices
// of the native platform packages that the bundle ships under `native/` (ADR 0082).
import { mkdirSync, mkdtempSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';

import { afterAll, beforeAll, describe, expect, it } from 'vitest';

// @ts-expect-error TS7016: repository scripts are plain .mjs files without declaration files
import * as noticesModule from '../../scripts/bundle-notices.mjs';

interface Notice {
  name: string;
  version: string;
  license: string;
  text: string | null;
}
interface Embedded {
  name: string;
  version: string;
  license: string;
  text: string;
  pattern: RegExp;
}
interface Lock {
  packages: Record<string, Record<string, unknown>>;
}
const {
  ALLOWED_LICENSES,
  EMBEDDED_NOTICES,
  NO_LICENSE_FILE_MARKER,
  assertAllowed,
  collectNotices,
  embeddedNotices,
  nativeNotice,
  packageKeyOf,
  productionClosure,
  renderNotices,
} = noticesModule as unknown as {
  ALLOWED_LICENSES: readonly string[];
  EMBEDDED_NOTICES: readonly Embedded[];
  NO_LICENSE_FILE_MARKER: string;
  assertAllowed: (notices: Notice[]) => void;
  collectNotices: (opts: {
    moduleIds: string[];
    bundleText?: string;
    includeWeb?: boolean;
    lock?: Lock;
    root?: string;
    table?: readonly Embedded[];
    nativePackages?: readonly Notice[];
  }) => Notice[];
  embeddedNotices: (text: string, table?: readonly Embedded[]) => Notice[];
  nativeNotice: (files: ReadonlyMap<string, Buffer>) => Notice;
  packageKeyOf: (id: string, root?: string) => string | null;
  productionClosure: (lock: Lock, start: string) => string[];
  renderNotices: (notices: Notice[]) => string;
};

/** A synthetic workspace: `packages/web` -> zeta, alpha (alpha nests its own beta), a workspace link, a dev-only tool. */
const LOCK: Lock = {
  packages: {
    '': { name: 'fixture-root', devDependencies: { devtool: '1.0.0' } },
    'packages/web': {
      name: '@fixture/web',
      dependencies: { zeta: '1.0.0', alpha: '2.0.0', '@fixture/shared': '1.0.0' },
      devDependencies: { devtool: '1.0.0' },
    },
    'packages/shared': { name: '@fixture/shared', dependencies: { '@scope/gamma': '3.0.0' } },
    'node_modules/@fixture/shared': { resolved: 'packages/shared', link: true },
    'node_modules/zeta': { version: '1.0.0', license: 'MIT' },
    'node_modules/alpha': { version: '2.0.0', license: 'ISC', dependencies: { beta: '^2.0.0' } },
    'node_modules/alpha/node_modules/beta': { version: '2.1.0', license: 'BSD-3-Clause' },
    'node_modules/beta': { version: '1.0.0', license: 'GPL-3.0-only', dev: true },
    'node_modules/@scope/gamma': {
      version: '3.0.0',
      license: 'Apache-2.0',
      peerDependencies: { zeta: '*', ghost: '*' },
      peerDependenciesMeta: { ghost: { optional: true } },
    },
    'node_modules/ghost': { version: '9.0.0', license: 'MIT' },
    'node_modules/devtool': { version: '1.0.0', license: 'GPL-3.0-only', dev: true },
  },
};

let root = '';

beforeAll(() => {
  root = mkdtempSync(join(tmpdir(), 'mcs-notices-'));
  writeFileSync(join(root, 'FIXTURE.md'), 'Synthetic test data generated by bundle-notices.test.ts. Not real data.\n');
  const pkg = (key: string, files: Record<string, string>): void => {
    const dir = join(root, ...key.split('/'));
    mkdirSync(dir, { recursive: true });
    for (const [name, text] of Object.entries(files)) writeFileSync(join(dir, name), text);
  };
  pkg('node_modules/zeta', { 'package.json': '{"name":"zeta"}', LICENSE: 'MIT License\r\n\r\nzeta text   \r\n' });
  pkg('node_modules/alpha', { 'package.json': '{"name":"alpha"}', 'LICENSE.md': 'ISC alpha text\n' });
  pkg('node_modules/alpha/node_modules/beta', { 'package.json': '{"name":"beta"}', 'license.txt': 'BSD beta text\n' });
  pkg('node_modules/@scope/gamma', { 'package.json': '{"name":"@scope/gamma"}' });
});

afterAll(() => {
  if (root !== '') rmSync(root, { recursive: true, force: true });
});

describe('productionClosure', () => {
  it('follows dependencies, workspace links, nested node_modules and required peers, never dev dependencies', () => {
    expect(productionClosure(LOCK, 'packages/web')).toEqual([
      'node_modules/@scope/gamma',
      'node_modules/alpha',
      'node_modules/alpha/node_modules/beta',
      'node_modules/zeta',
    ]);
  });
});

describe('packageKeyOf', () => {
  it('maps a module path to its innermost package and first-party code to null', () => {
    expect(packageKeyOf(join(root, 'node_modules', 'alpha', 'node_modules', 'beta', 'index.js'), root)).toBe(
      'node_modules/alpha/node_modules/beta',
    );
    expect(packageKeyOf(join(root, 'node_modules', '@scope', 'gamma', 'dist', 'a.js'), root)).toBe(
      'node_modules/@scope/gamma',
    );
    expect(packageKeyOf(join(root, 'packages', 'shared', 'src', 'x.ts'), root)).toBeNull();
    expect(packageKeyOf('\0rolldown/runtime.js', root)).toBeNull();
  });
});

describe('collectNotices and renderNotices', () => {
  const collect = (extra: { moduleIds?: string[]; bundleText?: string; table?: readonly Embedded[] } = {}): Notice[] =>
    collectNotices({ moduleIds: [], includeWeb: true, lock: LOCK, root, table: [], ...extra });

  it('lists the packages sorted by name with their licence text, LF only and trimmed', () => {
    const notices = collect();
    expect(notices.map((n) => `${n.name}@${n.version} ${n.license}`)).toEqual([
      '@scope/gamma@3.0.0 Apache-2.0',
      'alpha@2.0.0 ISC',
      'beta@2.1.0 BSD-3-Clause',
      'zeta@1.0.0 MIT',
    ]);
    expect(notices.find((n) => n.name === 'zeta')?.text).toBe('MIT License\n\nzeta text');
  });

  it('gives a package without a licence file the marker line', () => {
    const text = renderNotices(collect());
    const block = text.slice(text.indexOf('@scope/gamma 3.0.0'));
    expect(block.split('\n').slice(0, 4)).toEqual([
      '@scope/gamma 3.0.0',
      'License: Apache-2.0',
      '',
      NO_LICENSE_FILE_MARKER,
    ]);
  });

  it('renders the same text twice: LF only, no dates, one trailing newline', () => {
    const a = renderNotices(collect());
    expect(renderNotices(collect())).toBe(a);
    expect(a).not.toContain('\r');
    expect(a).not.toMatch(/\b(19|20)\d\d-\d\d-\d\d\b/);
    expect(a.endsWith('\n') && !a.endsWith('\n\n')).toBe(true);
  });

  it('names every folder with third-party code in the header: the Node files, web/ and native/', () => {
    const header = renderNotices(collect()).split('\n').slice(0, 4).join('\n');
    expect(header).toContain('mcs-cli.mjs, mcs-server.mjs, mcs-hook.mjs, web/ and native/');
  });

  it('adds the packages of the bundled modules and deduplicates', () => {
    const ids = [join(root, 'node_modules', 'zeta', 'index.js'), join(root, 'node_modules', 'zeta', 'other.js')];
    const notices = collectNotices({ moduleIds: ids, includeWeb: false, lock: LOCK, root, table: [] });
    expect(notices.map((n) => n.name)).toEqual(['zeta']);
  });

  it('fails on a licence outside the allow list and accepts an OR expression with one allowed choice', () => {
    const ids = [join(root, 'node_modules', 'devtool', 'index.js')];
    expect(() => collectNotices({ moduleIds: ids, includeWeb: false, lock: LOCK, root, table: [] })).toThrow(
      /licence not in the allow list: devtool@1\.0\.0 \(GPL-3\.0-only\)/,
    );
    expect(() => {
      assertAllowed([{ name: 'x', version: '1', license: '(MIT OR GPL-3.0-only)', text: null }]);
    }).not.toThrow();
    expect(ALLOWED_LICENSES).toEqual([
      'MIT',
      'ISC',
      'BSD-2-Clause',
      'BSD-3-Clause',
      'Apache-2.0',
      '0BSD',
      'BlueOak-1.0.0',
      'CC0-1.0',
      'Unlicense',
    ]);
  });
});

describe('the native platform packages (ADR 0082)', () => {
  /** The staged files of a package as `nativeFilesOf` returns them: LF text, a `package.json` and a `LICENSE`. */
  const staged = (manifest: Record<string, unknown>, license: string | null): Map<string, Buffer> => {
    const files = new Map<string, Buffer>([['package.json', Buffer.from(`${JSON.stringify(manifest)}\n`)]]);
    if (license !== null) files.set('LICENSE', Buffer.from(license));
    return files;
  };
  const NATIVE = { name: '@native/pty-win32-x64', version: '1.0.0', license: 'MIT' };

  it('takes the name, version and SPDX id from package.json and the text from LICENSE, trimmed like any other notice', () => {
    expect(nativeNotice(staged(NATIVE, 'MIT License   \n\nnative text  \n\n'))).toEqual({
      name: '@native/pty-win32-x64',
      version: '1.0.0',
      license: 'MIT',
      text: 'MIT License\n\nnative text',
    });
  });

  it('gives a package without a LICENSE file the marker line and a package without a licence field the id UNKNOWN', () => {
    expect(nativeNotice(staged(NATIVE, null)).text).toBeNull();
    expect(nativeNotice(staged({ name: 'n', version: '1.0.0' }, 'x')).license).toBe('UNKNOWN');
    expect(() => nativeNotice(new Map())).toThrow(/package\.json/);
    expect(() => nativeNotice(new Map([['package.json', Buffer.from('{ not json')]]))).toThrow(/package\.json/);
  });

  it('adds the native packages to the others, sorted by name, once each', () => {
    const one = nativeNotice(staged(NATIVE, 'MIT License\n\nnative text'));
    const other = nativeNotice(
      staged({ name: '@native/pty-win32-arm64', version: '1.0.0', license: 'MIT' }, 'MIT arm'),
    );
    const notices = collectNotices({
      moduleIds: [],
      includeWeb: true,
      lock: LOCK,
      root,
      table: [],
      nativePackages: [one, other, one],
    });
    expect(notices.map((n) => `${n.name}@${n.version}`)).toEqual([
      '@native/pty-win32-arm64@1.0.0',
      '@native/pty-win32-x64@1.0.0',
      '@scope/gamma@3.0.0',
      'alpha@2.0.0',
      'beta@2.1.0',
      'zeta@1.0.0',
    ]);
    const text = renderNotices(notices);
    expect(text).toContain('@native/pty-win32-x64 1.0.0\nLicense: MIT\n\nMIT License\n\nnative text');
  });

  it('applies the licence allow list to a native package too', () => {
    const gpl = nativeNotice(staged({ name: '@native/pty', version: '1.0.0', license: 'GPL-3.0-only' }, 'GPL text'));
    expect(() =>
      collectNotices({ moduleIds: [], includeWeb: false, lock: LOCK, root, table: [], nativePackages: [gpl] }),
    ).toThrow(/licence not in the allow list: @native\/pty@1\.0\.0 \(GPL-3\.0-only\)/);
  });
});

describe('embedded notices', () => {
  const vendored: Embedded = {
    name: 'vendored-lib',
    version: '1.2.3',
    license: 'MIT',
    text: 'MIT License\n\nvendored text',
    pattern: /VENDORED_LIB_SIGNATURE/,
  };

  it('adds the notice of vendored code that the bundle text contains, and only then', () => {
    const notices = collectNotices({
      moduleIds: [],
      includeWeb: false,
      lock: LOCK,
      root,
      bundleText: 'var x = "VENDORED_LIB_SIGNATURE";',
      table: [vendored],
    });
    expect(notices).toEqual([
      { name: 'vendored-lib', version: '1.2.3', license: 'MIT', text: 'MIT License\n\nvendored text' },
    ]);
    expect(embeddedNotices('nothing here', [vendored])).toEqual([]);
  });

  it('fails when the bundle matches a pattern whose notice is incomplete', () => {
    expect(() => embeddedNotices('VENDORED_LIB_SIGNATURE', [{ ...vendored, text: '' }])).toThrow(
      /contains vendored-lib but its notice is incomplete/,
    );
  });

  it('keeps every entry of the real table complete', () => {
    for (const entry of EMBEDDED_NOTICES) {
      expect(entry.pattern).toBeInstanceOf(RegExp);
      expect(ALLOWED_LICENSES).toContain(entry.license);
      expect(entry.text.trim()).not.toBe('');
    }
  });
});

// ---- the libraries that the v2 line of the MCP SDK inlines (ADR 0060, ADR 0063 item 6) ----------------------------------------
// With the literal v1 package (`@modelcontextprotocol/sdk`) these libraries are separate packages of the lockfile closure and the
// entries never match; with the v2 package (`@modelcontextprotocol/server`) they sit inside the SDK's own dist files and nothing but
// this table lists them. The texts below are synthetic stand-ins that carry the code signature of each library.
describe('the embedded notices of the MCP SDK libraries', () => {
  const SIGNATURES: Readonly<Record<string, string>> = {
    ajv: 'throw new Error("CodeGen: name must be a valid identifier");',
    'ajv-formats': 'exports.fullFormats = {};',
    'content-type': 'var PARAM_REGEXP = /x/g;',
    'fast-deep-equal': 'module.exports = function equal(a, b) { return a === b; };',
    'fast-uri': 'const supportedSchemeNames = ["http"];',
    'json-schema-traverse': 'traverse.skipKeywords = { default: true };',
  };
  const INLINED_TEXT = Object.values(SIGNATURES).join('\n');
  const names = (notices: readonly { name: string }[]): string[] => notices.map((n) => n.name).sort();

  it('lists Ajv, its format and helper libraries and content-type when the SDK inlines them', () => {
    expect(names(embeddedNotices(INLINED_TEXT))).toEqual(Object.keys(SIGNATURES));
  });

  it('fails the check of an inlined library whose entry is missing from the table', () => {
    // the table is the only record of a vendored library, so a bundle that holds one must be covered entry by entry
    for (const name of Object.keys(SIGNATURES)) {
      const covered = EMBEDDED_NOTICES.some((entry) => entry.name === name && entry.pattern.test(INLINED_TEXT));
      expect(covered, `${name} has no entry that matches its code`).toBe(true);
    }
  });

  it('gives every entry a name, a version, an SPDX id of the allow list and a licence text with its copyright line', () => {
    for (const entry of EMBEDDED_NOTICES) {
      expect(entry.version, entry.name).toMatch(/^\d+\.\d+\.\d+$/);
      expect(['MIT', 'BSD-3-Clause'], entry.name).toContain(entry.license);
      expect(entry.text, entry.name).toMatch(/Copyright \(c\)|Copyright\(c\)/i);
      expect(entry.text, entry.name).not.toContain('\r');
    }
    expect(EMBEDDED_NOTICES.find((e) => e.name === 'fast-uri')?.license).toBe('BSD-3-Clause');
    expect(EMBEDDED_NOTICES.find((e) => e.name === 'fast-uri')?.text).toContain(
      'Redistribution and use in source and binary forms',
    );
    expect(EMBEDDED_NOTICES.find((e) => e.name === 'ajv')?.text).toContain('Permission is hereby granted');
  });

  it('never matches when the library is a separate package of the bundle (the v1 package)', () => {
    const regions = Object.keys(SIGNATURES)
      .map((name) => `//#region npm/${name}/dist/index.js\n${SIGNATURES[name] ?? ''}`)
      .join('\n');
    expect(embeddedNotices(regions)).toEqual([]);
    // a copy nested below the SDK is written as npm/@modelcontextprotocol/sdk/npm/<name>/ by the bundle normaliser
    const nested = Object.keys(SIGNATURES)
      .map((name) => `//#region npm/@modelcontextprotocol/sdk/npm/${name}/lib/a.js\n${SIGNATURES[name] ?? ''}`)
      .join('\n');
    expect(embeddedNotices(nested)).toEqual([]);
  });

  it('matches only the libraries that are inlined, and an unrelated bundle matches nothing', () => {
    const onlyAjv = `//#region npm/fast-uri/index.js\n${SIGNATURES['fast-uri'] ?? ''}\n${SIGNATURES['ajv'] ?? ''}`;
    expect(names(embeddedNotices(onlyAjv))).toEqual(['ajv']);
    expect(embeddedNotices('console.log("no vendored code here");')).toEqual([]);
  });

  it('adds the notices of an inlined bundle to the generated text, once each, with the licence text', () => {
    const notices = collectNotices({ moduleIds: [], includeWeb: false, lock: LOCK, root, bundleText: INLINED_TEXT });
    expect(names(notices)).toEqual(Object.keys(SIGNATURES));
    const text = renderNotices(notices);
    for (const name of Object.keys(SIGNATURES)) {
      expect(
        text.split('\n').filter((line) => line.startsWith(`${name} `)),
        name,
      ).toHaveLength(1);
    }
    expect(text).toContain('Redistribution and use in source and binary forms');
  });

  it('lists the SDK itself once when it is a module of the bundle, through the lockfile closure', () => {
    const lock: Lock = {
      packages: {
        '': { name: 'fixture-root' },
        'node_modules/@modelcontextprotocol/sdk': { version: '1.32.1', license: 'MIT' },
        'node_modules/ajv': { version: '8.20.0', license: 'MIT' },
      },
    };
    const ids = [
      join(root, 'node_modules', '@modelcontextprotocol', 'sdk', 'dist', 'esm', 'server', 'index.js'),
      join(root, 'node_modules', '@modelcontextprotocol', 'sdk', 'dist', 'esm', 'types.js'),
      join(root, 'node_modules', 'ajv', 'dist', 'ajv.js'),
    ];
    const notices = collectNotices({
      moduleIds: ids,
      includeWeb: false,
      lock,
      root,
      bundleText: INLINED_TEXT.replace('throw', '//#region npm/ajv/x\nthrow'),
    });
    expect(notices.filter((n) => n.name === '@modelcontextprotocol/sdk')).toHaveLength(1);
    expect(notices.filter((n) => n.name === 'ajv')).toHaveLength(1);
  });
});

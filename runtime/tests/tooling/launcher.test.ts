// The bundle-first launcher `skills/monitoring-claude-sessions/scripts/mcs.mjs` (ADR 0062 item 4): the pure helpers, the
// in-process hand-over to a (fake) bundle and a checkout's `dist`, the floor check on a spoofed old Node, the real committed
// bundle on a hermetic instance under a path with spaces and non-ASCII characters, and static checks of the file itself.
import { execFile } from 'node:child_process';
import { cpSync, mkdirSync, mkdtempSync, readFileSync, realpathSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { pathToFileURL } from 'node:url';

import { allocatePort, hermeticEnv, snapshotTree } from '@mcs/testkit';
import { Linter } from 'eslint';
import { afterAll, describe, expect, it } from 'vitest';

const REPO = resolve(import.meta.dirname, '..', '..', '..');
const SKILLDIR = join(REPO, 'skills', 'monitoring-claude-sessions');
const LAUNCHER = join(SKILLDIR, 'scripts', 'mcs.mjs');

interface LauncherModule {
  NODE_FLOOR: string;
  meetsNodeFloor(version: string, floor?: string): boolean;
  floorMessage(version: string): string;
  noRuntimeMessage(skillDir: string): string;
  chooseMode(
    forced: string | undefined,
    hasBundle: boolean,
    hasDist: boolean,
    skillDir?: string,
  ): { mode?: 'bundle' | 'dev'; error?: string };
  versionLine(mode: 'bundle' | 'dev', jsonText: string): string | null;
  isVersionFastPath(argv: readonly string[]): boolean;
}

const launcher = (await import(pathToFileURL(LAUNCHER).href)) as LauncherModule;

const temps: string[] = [];
afterAll(() => {
  for (const dir of temps) rmSync(dir, { recursive: true, force: true, maxRetries: 5, retryDelay: 100 });
});

/** A fresh temp folder by its real path (the launcher sees its own path resolved, e.g. no Windows 8.3 short names). */
function tempRoot(label: string): string {
  const dir = realpathSync.native(mkdtempSync(join(tmpdir(), `mcs-launcher-${label}-`)));
  temps.push(dir);
  writeFileSync(
    join(dir, 'FIXTURE.md'),
    'Synthetic test data generated by tests/tooling/launcher.test.ts. Not real data.\n',
  );
  return dir;
}

function write(path: string, text: string): void {
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, text);
}

/** Records its arguments as JSON into the file named by `FAKE_RECORD` and returns `code`. */
function fakeCli(tag: string, code: number): string {
  return [
    "import { writeFileSync } from 'node:fs';",
    'export async function main(argv, paths) {',
    `  writeFileSync(process.env.FAKE_RECORD, JSON.stringify({ tag: '${tag}', argv, paths }));`,
    `  return ${String(code)};`,
    '}',
    '',
  ].join('\n');
}

interface Run {
  code: number;
  stdout: string;
  stderr: string;
}

function runNode(args: readonly string[], env: Record<string, string>, cwd: string): Promise<Run> {
  return new Promise((done) => {
    execFile(
      process.execPath,
      [...args],
      { cwd, env, windowsHide: true, timeout: 60_000, encoding: 'utf8' },
      (error, stdout, stderr) => {
        const code = error === null ? 0 : typeof error.code === 'number' ? error.code : -1;
        done({ code, stdout, stderr });
      },
    );
  });
}

/** The parent's environment without any `MCS_*` / `CLAUDE_*` variable, plus `extra`. */
function cleanEnv(extra: Record<string, string> = {}): Record<string, string> {
  const env: Record<string, string> = {};
  for (const [key, value] of Object.entries(process.env)) {
    if (value !== undefined && !/^(MCS_|CLAUDE_)/i.test(key)) env[key] = value;
  }
  return { ...env, MCS_HOOK_DISABLE: '1', ...extra };
}

/** `<root>/repo/skills/mcs/` with the real launcher, optional fake bundle and optional fake checkout `dist`. */
function fakeCheckout(root: string, opts: { bundle?: string; dist?: string }): { skillDir: string; launcher: string } {
  const skillDir = join(root, 'repo', 'skills', 'mcs');
  const copy = join(skillDir, 'scripts', 'mcs.mjs');
  write(copy, readFileSync(LAUNCHER, 'utf8'));
  if (opts.bundle !== undefined) {
    write(join(skillDir, 'bundle', 'mcs-cli.mjs'), opts.bundle);
    write(join(skillDir, 'bundle', '.mcs-build.json'), '{"schemaVersion":1,"runtimeVersion":"8.8.8"}\n');
  }
  if (opts.dist !== undefined) {
    write(join(root, 'repo', 'runtime', 'packages', 'cli', 'dist', 'main.js'), opts.dist);
    write(join(root, 'repo', 'runtime', 'package.json'), '{"name":"fake","version":"9.9.9","type":"module"}\n');
  }
  return { skillDir, launcher: copy };
}

describe('launcher helpers', () => {
  it('applies the Node floor 22.22.0', () => {
    expect(launcher.NODE_FLOOR).toBe('22.22.0');
    expect(launcher.meetsNodeFloor('22.21.9')).toBe(false);
    expect(launcher.meetsNodeFloor('22.22.0')).toBe(true);
    expect(launcher.meetsNodeFloor('24.0.0')).toBe(true);
    expect(launcher.meetsNodeFloor('26.1.0')).toBe(true);
    expect(launcher.meetsNodeFloor('v24.1.2')).toBe(true);
    expect(launcher.meetsNodeFloor('18.20.4')).toBe(false);
    expect(launcher.meetsNodeFloor('22.9.0')).toBe(false);
    for (const garbage of ['', 'garbage', '24', '24.x.0', '22.22'])
      expect(launcher.meetsNodeFloor(garbage), garbage).toBe(false);
  });

  it('prints the exact floor message', () => {
    expect(launcher.floorMessage('20.11.1')).toBe(
      'ERROR: Node >= 22.22.0 is required (found 20.11.1); install the Node 24 LTS',
    );
  });

  it('chooses the mode: forced, bundle first, then dev, else the documented error', () => {
    expect(launcher.chooseMode(undefined, true, true)).toEqual({ mode: 'bundle' });
    expect(launcher.chooseMode('', true, false)).toEqual({ mode: 'bundle' });
    expect(launcher.chooseMode(undefined, false, true)).toEqual({ mode: 'dev' });
    expect(launcher.chooseMode('dev', true, true)).toEqual({ mode: 'dev' });
    expect(launcher.chooseMode('bundle', true, true)).toEqual({ mode: 'bundle' });
    expect(launcher.chooseMode(undefined, false, false, 'S').error).toBe(launcher.noRuntimeMessage('S'));
    expect(launcher.chooseMode('bundle', false, true).error).toMatch(/^ERROR: MCS_LAUNCHER_MODE=bundle /);
    expect(launcher.chooseMode('dev', true, false).error).toMatch(/^ERROR: MCS_LAUNCHER_MODE=dev /);
    expect(launcher.chooseMode('other', true, true).error).toBe(
      'ERROR: MCS_LAUNCHER_MODE must be bundle or dev (found other)',
    );
    expect(launcher.noRuntimeMessage('S')).toMatch(/^ERROR: no runtime found in S: /);
    expect(launcher.noRuntimeMessage('S')).toContain('npm ci && npm run build');
    expect(launcher.noRuntimeMessage('S')).toContain('install the skill from a release');
  });

  it('builds the version line from the build stamp or the package file', () => {
    expect(launcher.versionLine('bundle', '{"runtimeVersion":"4.0.0"}')).toBe('mcs 4.0.0');
    expect(launcher.versionLine('dev', '{"version":"4.1.0"}')).toBe('mcs 4.1.0');
    expect(launcher.versionLine('bundle', '{"version":"4.1.0"}')).toBeNull();
    expect(launcher.versionLine('dev', 'not json')).toBeNull();
    expect(launcher.versionLine('dev', 'null')).toBeNull();
    expect(launcher.isVersionFastPath(['--version'])).toBe(true);
    expect(launcher.isVersionFastPath(['version', '--short'])).toBe(true);
    expect(launcher.isVersionFastPath(['version'])).toBe(false);
    expect(launcher.isVersionFastPath(['version', '--short', '--json'])).toBe(false);
    expect(launcher.isVersionFastPath([])).toBe(false);
  });
});

describe('launcher hand-over (fake runtimes)', () => {
  it('passes the argv and { launcherPath, skillDir, runtimeDir } to the bundle and propagates the exit code', async () => {
    const root = tempRoot('bundle');
    const fake = fakeCheckout(root, { bundle: fakeCli('bundle', 7) });
    const record = join(root, 'record.json');
    const run = await runNode([fake.launcher, 'status', '--json'], cleanEnv({ FAKE_RECORD: record }), root);
    expect(run.stderr).toBe('');
    expect(run.code).toBe(7);
    expect(JSON.parse(readFileSync(record, 'utf8'))).toEqual({
      tag: 'bundle',
      argv: ['status', '--json'],
      paths: { launcherPath: fake.launcher, skillDir: fake.skillDir, runtimeDir: join(fake.skillDir, 'bundle') },
    });
  });

  it('answers --version and version --short from the build stamp without loading the bundle', async () => {
    const root = tempRoot('version');
    const fake = fakeCheckout(root, { bundle: "throw new Error('must not load');\n" });
    for (const args of [['--version'], ['version', '--short']]) {
      const run = await runNode([fake.launcher, ...args], cleanEnv(), root);
      expect(run).toEqual({ code: 0, stdout: 'mcs 8.8.8\n', stderr: '' });
    }
  });

  it('runs the checkout dist with MCS_LAUNCHER_MODE=dev, the bundle by default', async () => {
    const root = tempRoot('dev');
    const fake = fakeCheckout(root, { bundle: fakeCli('bundle', 3), dist: fakeCli('dev', 4) });
    const record = join(root, 'record.json');
    const dev = await runNode(
      [fake.launcher, 'help'],
      cleanEnv({ FAKE_RECORD: record, MCS_LAUNCHER_MODE: 'dev' }),
      root,
    );
    expect(dev.code).toBe(4);
    const recorded = JSON.parse(readFileSync(record, 'utf8')) as { tag: string; paths: { runtimeDir: string } };
    expect(recorded.tag).toBe('dev');
    expect(recorded.paths.runtimeDir).toBe(join(root, 'repo', 'runtime'));
    const version = await runNode([fake.launcher, '--version'], cleanEnv({ MCS_LAUNCHER_MODE: 'dev' }), root);
    expect(version.stdout).toBe('mcs 9.9.9\n');
    const byDefault = await runNode([fake.launcher, 'help'], cleanEnv({ FAKE_RECORD: record }), root);
    expect(byDefault.code).toBe(3);
    expect((JSON.parse(readFileSync(record, 'utf8')) as { tag: string }).tag).toBe('bundle');
  });

  it('fails with the documented error and exit 1 when there is neither a bundle nor a dist', async () => {
    const root = tempRoot('none');
    const fake = fakeCheckout(root, {});
    const run = await runNode([fake.launcher, 'status'], cleanEnv(), root);
    expect(run.code).toBe(1);
    expect(run.stdout).toBe('');
    expect(run.stderr).toBe(`${launcher.noRuntimeMessage(fake.skillDir)}\n`);
  });

  it('checks the floor before it imports anything (spoofed old Node, bundle that throws on import)', async () => {
    const root = tempRoot('floor');
    const fake = fakeCheckout(root, { bundle: "throw new Error('bundle import failed');\n" });
    const preload = join(root, 'old-node.mjs');
    write(
      preload,
      "Object.defineProperty(process, 'versions', { value: { ...process.versions, node: '20.11.1' } });\n",
    );
    const old = await runNode(['--import', pathToFileURL(preload).href, fake.launcher, 'status'], cleanEnv(), root);
    expect(old).toEqual({ code: 1, stdout: '', stderr: `${launcher.floorMessage('20.11.1')}\n` });
    // control: on the real Node the same bundle reaches the import and fails as an internal launcher error
    const current = await runNode([fake.launcher, 'status'], cleanEnv(), root);
    expect(current.code).toBe(1);
    expect(current.stderr).toBe('ERROR: internal launcher error: bundle import failed\n');
  });
});

describe('launcher with the committed bundle', () => {
  it('runs --version, init, start, verify, status and stop from a copied skill folder and writes nothing into it', async () => {
    const root = tempRoot('real');
    const skillDir = join(root, 'skill folder ñé ü', 'monitoring-claude-sessions');
    cpSync(SKILLDIR, skillDir, { recursive: true });
    const before = snapshotTree(skillDir);
    const copy = join(skillDir, 'scripts', 'mcs.mjs');
    const repo = join(root, 'repo');
    mkdirSync(repo, { recursive: true });
    const env = hermeticEnv(join(root, 'env'));
    for (const dir of [env['HOME'], env['MCS_HOME'], env['CLAUDE_CONFIG_DIR']])
      mkdirSync(dir ?? root, { recursive: true });
    const port = await allocatePort();
    const mcs = (...args: string[]): Promise<Run> => runNode([copy, ...args], env, root);
    const task = ['--task', 'demo', '--repo', repo];
    const stamp = JSON.parse(readFileSync(join(SKILLDIR, 'bundle', '.mcs-build.json'), 'utf8')) as {
      runtimeVersion: string;
    };

    expect(await mcs('--version')).toEqual({ code: 0, stdout: `mcs ${stamp.runtimeVersion}\n`, stderr: '' });
    const init = await mcs('init', '--slug', 'demo', '--name', 'FIXTURE demo', '--repo', repo, '--port', String(port));
    expect(init.code, init.stderr || init.stdout).toBe(0);
    let started = false;
    try {
      const start = await mcs('start', ...task);
      started = true;
      expect(start.code, start.stderr || start.stdout).toBe(0);
      expect(start.stdout).toContain(String(port));
      const verify = await mcs('verify', ...task);
      expect(verify.code, verify.stderr || verify.stdout).toBe(0);
      const status = await mcs('status', ...task, '--json');
      expect(status.code, status.stderr).toBe(0);
      expect(() => JSON.parse(status.stdout) as unknown).not.toThrow();
      // two launchers at once both succeed
      const both = await Promise.all([mcs('version'), mcs('status', ...task)]);
      for (const run of both) expect(run.code, run.stderr || run.stdout).toBe(0);
    } finally {
      if (started) {
        const stop = await mcs('stop', ...task);
        expect(stop.code, stop.stderr || stop.stdout).toBe(0);
      }
    }
    expect(snapshotTree(skillDir)).toBe(before);
  }, 120_000);
});

describe('launcher static rules', () => {
  const source = readFileSync(LAUNCHER, 'utf8');

  it('imports only node:* modules and never spawns a process', () => {
    const statics = [...source.matchAll(/^\s*import\s[^'"]*['"]([^'"]+)['"]/gm)].map((m) => m[1]);
    expect(statics.length).toBeGreaterThan(0);
    for (const name of statics) expect(name, name).toMatch(/^node:/);
    const code = source.replace(/\/\*[\s\S]*?\*\/|^\s*\/\/.*$/gm, '');
    for (const word of ['child_process', 'spawn', 'execFile', 'execSync', 'fork(', 'require(']) {
      expect(code, word).not.toContain(word);
    }
    // `npm` appears only in the advice of the two error messages, never as a command the launcher runs
    for (const line of code.split('\n').filter((l) => /\bnpm\b/.test(l)))
      expect(line).toContain('npm ci && npm run build');
  });

  it('passes node --check', async () => {
    const run = await runNode(['--check', LAUNCHER], cleanEnv(), REPO);
    expect(run).toEqual({ code: 0, stdout: '', stderr: '' });
  });

  it('uses no syntax newer than ES2020', () => {
    const parse = (code: string) =>
      new Linter()
        .verify(code, [{ languageOptions: { ecmaVersion: 2020, sourceType: 'module' } }])
        .filter((m) => m.fatal);
    expect(parse(source)).toEqual([]);
    // negative controls: ES2022 top-level await and ES2021 logical assignment are rejected
    expect(parse('await Promise.resolve(1);\n')).toHaveLength(1);
    expect(parse('let a = 0;\na ||= 1;\n')).toHaveLength(1);
  });
});
